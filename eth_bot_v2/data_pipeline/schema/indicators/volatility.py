"""
Volatility Technical Indicators Schema

Defines the standardized schema for volatility-related
technical indicators generated by the Technical Indicator Engine.

These indicators measure market volatility, price expansion,
and contraction. They are consumed by Feature Engineering,
Dataset Builder, AI models, Strategy Engine, and Risk Engine.

This schema stores indicator values only.
Indicator calculations are performed by the Technical Indicator Engine.
"""

from dataclasses import dataclass
from datetime import datetime
from typing import Optional


@dataclass
class VolatilityIndicatorSchema:

    # ==========================================================
    # Asset Information
    # ==========================================================

    symbol: str

    timeframe: str

    timestamp: datetime

    # ==========================================================
    # Average True Range (ATR)
    # ==========================================================

    atr_14: Optional[float] = None

    atr_21: Optional[float] = None

    # ==========================================================
    # Bollinger Bands
    # ==========================================================

    bollinger_upper: Optional[float] = None

    bollinger_middle: Optional[float] = None

    bollinger_lower: Optional[float] = None

    bollinger_bandwidth: Optional[float] = None

    bollinger_percent_b: Optional[float] = None

    # ==========================================================
    # Keltner Channels
    # ==========================================================

    keltner_upper: Optional[float] = None

    keltner_middle: Optional[float] = None

    keltner_lower: Optional[float] = None

    # ==========================================================
    # Donchian Channels
    # ==========================================================

    donchian_upper: Optional[float] = None

    donchian_middle: Optional[float] = None

    donchian_lower: Optional[float] = None

    # ==========================================================
    # Historical Volatility
    # ==========================================================

    historical_volatility: Optional[float] = None

    # ==========================================================
    # Chaikin Volatility
    # ==========================================================

    chaikin_volatility: Optional[float] = None

    # ==========================================================
    # Metadata
    # ==========================================================

    indicator_version: str = "1.0"

    calculated_at: Optional[datetime] = None

    # ==========================================================
    # Convenience Properties
    # ==========================================================

    @property
    def high_volatility(self) -> bool:
        return (
            self.atr_14 is not None
            and self.atr_21 is not None
            and self.atr_14 > self.atr_21
        )

    @property
    def low_volatility(self) -> bool:
        return (
            self.atr_14 is not None
            and self.atr_21 is not None
            and self.atr_14 < self.atr_21
        )

    @property
    def bollinger_squeeze(self) -> bool:
        return (
            self.bollinger_bandwidth is not None
            and self.bollinger_bandwidth < 0.05
        )

    @property
    def bollinger_expansion(self) -> bool:
        return (
            self.bollinger_bandwidth is not None
            and self.bollinger_bandwidth > 0.15
        )

    @property
    def above_upper_band(self) -> bool:
        return (
            self.bollinger_upper is not None
            and self.bollinger_percent_b is not None
            and self.bollinger_percent_b > 1
        )

    @property
    def below_lower_band(self) -> bool:
        return (
            self.bollinger_lower is not None
            and self.bollinger_percent_b is not None
            and self.bollinger_percent_b < 0
        )

    @property
    def inside_keltner_channel(self) -> bool:
        return (
            self.keltner_upper is not None
            and self.keltner_lower is not None
        )

    @property
    def inside_donchian_channel(self) -> bool:
        return (
            self.donchian_upper is not None
            and self.donchian_lower is not None
        )