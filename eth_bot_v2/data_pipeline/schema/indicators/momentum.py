"""
Momentum Technical Indicators Schema

Stores calculated momentum indicators generated by the
Technical Indicator Engine.

These indicators measure the speed and strength of price
movements and are later consumed by Feature Engineering,
Dataset Builder, and AI models.

This schema stores indicator values only.
No calculations are performed here.
"""

from dataclasses import dataclass
from datetime import datetime
from typing import Optional


@dataclass
class MomentumIndicatorSchema:

    # ==========================================================
    # Asset Information
    # ==========================================================

    symbol: str

    timeframe: str

    timestamp: datetime

    # ==========================================================
    # Relative Strength Index (RSI)
    # ==========================================================

    rsi_14: Optional[float] = None

    rsi_21: Optional[float] = None

    # ==========================================================
    # Stochastic RSI
    # ==========================================================

    stochastic_rsi: Optional[float] = None

    stochastic_k: Optional[float] = None

    stochastic_d: Optional[float] = None

    # ==========================================================
    # Commodity Channel Index (CCI)
    # ==========================================================

    cci_20: Optional[float] = None

    # ==========================================================
    # Rate of Change (ROC)
    # ==========================================================

    roc_14: Optional[float] = None

    # ==========================================================
    # Momentum
    # ==========================================================

    momentum_10: Optional[float] = None

    momentum_20: Optional[float] = None

    # ==========================================================
    # Williams %R
    # ==========================================================

    williams_r: Optional[float] = None

    # ==========================================================
    # True Strength Index (TSI)
    # ==========================================================

    tsi: Optional[float] = None

    tsi_signal: Optional[float] = None

    # ==========================================================
    # Ultimate Oscillator
    # ==========================================================

    ultimate_oscillator: Optional[float] = None

    # ==========================================================
    # Awesome Oscillator
    # ==========================================================

    awesome_oscillator: Optional[float] = None

    # ==========================================================
    # Percentage Price Oscillator (PPO)
    # ==========================================================

    ppo: Optional[float] = None

    ppo_signal: Optional[float] = None

    ppo_histogram: Optional[float] = None

    # ==========================================================
    # Metadata
    # ==========================================================

    indicator_version: str = "1.0"

    calculated_at: Optional[datetime] = None

    # ==========================================================
    # Convenience Properties
    # ==========================================================

    @property
    def rsi_overbought(self) -> bool:
        return (
            self.rsi_14 is not None
            and self.rsi_14 >= 70
        )

    @property
    def rsi_oversold(self) -> bool:
        return (
            self.rsi_14 is not None
            and self.rsi_14 <= 30
        )

    @property
    def bullish_momentum(self) -> bool:
        return (
            self.momentum_10 is not None
            and self.momentum_10 > 0
        )

    @property
    def bearish_momentum(self) -> bool:
        return (
            self.momentum_10 is not None
            and self.momentum_10 < 0
        )

    @property
    def bullish_tsi(self) -> bool:
        return (
            self.tsi is not None
            and self.tsi_signal is not None
            and self.tsi > self.tsi_signal
        )

    @property
    def bearish_tsi(self) -> bool:
        return (
            self.tsi is not None
            and self.tsi_signal is not None
            and self.tsi < self.tsi_signal
        )