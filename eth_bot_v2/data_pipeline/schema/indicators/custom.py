"""
Custom Technical Indicators Schema

Defines proprietary indicators and custom-derived signals
generated by the Technical Indicator Engine.

Unlike standard technical indicators (RSI, MACD, ATR, etc.),
these indicators are designed specifically for the ETH Bot
trading system.

This schema stores calculated values only.
Indicator calculations are performed by the Technical Indicator Engine.
"""

from dataclasses import dataclass
from datetime import datetime
from typing import Optional


@dataclass
class CustomIndicatorSchema:

    # ==========================================================
    # Asset Information
    # ==========================================================

    symbol: str

    timeframe: str

    timestamp: datetime

    # ==========================================================
    # Trend Scores
    # ==========================================================

    trend_score: Optional[float] = None

    trend_strength_score: Optional[float] = None

    trend_confidence: Optional[float] = None

    # ==========================================================
    # Momentum Scores
    # ==========================================================

    momentum_score: Optional[float] = None

    momentum_acceleration: Optional[float] = None

    reversal_probability: Optional[float] = None

    # ==========================================================
    # Volatility Scores
    # ==========================================================

    volatility_score: Optional[float] = None

    volatility_regime: Optional[str] = None

    breakout_probability: Optional[float] = None

    # ==========================================================
    # Volume Scores
    # ==========================================================

    volume_score: Optional[float] = None

    buying_pressure: Optional[float] = None

    selling_pressure: Optional[float] = None

    liquidity_score: Optional[float] = None

    # ==========================================================
    # Market Structure
    # ==========================================================

    market_regime: Optional[str] = None

    market_phase: Optional[str] = None

    trend_direction: Optional[str] = None

    support_strength: Optional[float] = None

    resistance_strength: Optional[float] = None

    # ==========================================================
    # Risk Metrics
    # ==========================================================

    risk_score: Optional[float] = None

    confidence_score: Optional[float] = None

    trade_quality_score: Optional[float] = None

    expected_reward_risk: Optional[float] = None

    # ==========================================================
    # AI Signals
    # ==========================================================

    long_probability: Optional[float] = None

    short_probability: Optional[float] = None

    hold_probability: Optional[float] = None

    signal_strength: Optional[float] = None

    # ==========================================================
    # Metadata
    # ==========================================================

    indicator_version: str = "1.0"

    calculated_at: Optional[datetime] = None

    # ==========================================================
    # Convenience Properties
    # ==========================================================

    @property
    def bullish(self):
        return (
            self.long_probability is not None
            and self.long_probability >= 0.7
        )

    @property
    def bearish(self):
        return (
            self.short_probability is not None
            and self.short_probability >= 0.7
        )

    @property
    def hold(self):
        return (
            self.hold_probability is not None
            and self.hold_probability >= 0.7
        )

    @property
    def high_quality_trade(self):
        return (
            self.trade_quality_score is not None
            and self.trade_quality_score >= 0.8
        )

    @property
    def low_risk_trade(self):
        return (
            self.risk_score is not None
            and self.risk_score <= 0.3
        )