"""
Volume Technical Indicators Schema

Defines the standardized schema for volume-related
technical indicators generated by the Technical Indicator Engine.

These indicators measure trading activity, money flow,
buying/selling pressure, and volume confirmation.

This schema stores calculated indicator values only.
Indicator calculations are performed by the Technical Indicator Engine.
"""

from dataclasses import dataclass
from datetime import datetime
from typing import Optional


@dataclass
class VolumeIndicatorSchema:

    # ==========================================================
    # Asset Information
    # ==========================================================

    symbol: str

    timeframe: str

    timestamp: datetime

    # ==========================================================
    # Volume
    # ==========================================================

    volume: Optional[float] = None

    volume_sma_20: Optional[float] = None

    volume_sma_50: Optional[float] = None

    volume_ema_20: Optional[float] = None

    volume_ema_50: Optional[float] = None

    volume_ratio: Optional[float] = None

    # ==========================================================
    # Volume Oscillator
    # ==========================================================

    volume_oscillator: Optional[float] = None

    # ==========================================================
    # On Balance Volume
    # ==========================================================

    obv: Optional[float] = None

    # ==========================================================
    # Volume Weighted Average Price
    # ==========================================================

    vwap: Optional[float] = None

    # ==========================================================
    # Chaikin Money Flow
    # ==========================================================

    cmf: Optional[float] = None

    # ==========================================================
    # Money Flow Index
    # ==========================================================

    mfi: Optional[float] = None

    # ==========================================================
    # Accumulation / Distribution Line
    # ==========================================================

    adl: Optional[float] = None

    # ==========================================================
    # Ease of Movement
    # ==========================================================

    ease_of_movement: Optional[float] = None

    # ==========================================================
    # Force Index
    # ==========================================================

    force_index: Optional[float] = None

    # ==========================================================
    # Negative / Positive Volume Index
    # ==========================================================

    positive_volume_index: Optional[float] = None

    negative_volume_index: Optional[float] = None

    # ==========================================================
    # Metadata
    # ==========================================================

    indicator_version: str = "1.0"

    calculated_at: Optional[datetime] = None

    # ==========================================================
    # Convenience Properties
    # ==========================================================

    @property
    def high_volume(self) -> bool:
        return (
            self.volume_ratio is not None
            and self.volume_ratio > 1.5
        )

    @property
    def low_volume(self) -> bool:
        return (
            self.volume_ratio is not None
            and self.volume_ratio < 0.7
        )

    @property
    def bullish_money_flow(self) -> bool:
        return (
            self.cmf is not None
            and self.cmf > 0
        )

    @property
    def bearish_money_flow(self) -> bool:
        return (
            self.cmf is not None
            and self.cmf < 0
        )

    @property
    def overbought_mfi(self) -> bool:
        return (
            self.mfi is not None
            and self.mfi >= 80
        )

    @property
    def oversold_mfi(self) -> bool:
        return (
            self.mfi is not None
            and self.mfi <= 20
        )

    @property
    def price_above_vwap(self) -> bool:
        """
        Requires comparison with market close price.
        Placeholder property.
        """
        return self.vwap is not None